export const dictionaries: Record<Lang, Record<Key, string>> = { fr, en };

export function detectLang(): Lang {
  try {
    const code = getLocales()[0]?.languageCode;
    return code === 'en' ? 'en' : 'fr';
  } catch {
    return 'fr';
  }
}

export function translate(lang: Lang, key: Key, vars?: Record<string, string | number>): string {
  let s = dictionaries[lang][key];
  if (vars) for (const k of Object.keys(vars)) s = s.split(`{${k}}`).join(String(vars[k]));
  return fill(lang, s);
}

export const dishName = (d: Dish, lang: Lang) => (lang === 'fr' ? d.fr : d.en);
export const compName = (c: Component, lang: Lang) => (lang === 'fr' ? c.fr : c.en);
export const allergenName = (a: Allergen, lang: Lang) => translate(lang, a);

const DAYS = {
  fr: ['dimanche', 'lundi', 'mardi', 'mercredi', 'jeudi', 'vendredi', 'samedi'],
  en: ['Sunday', 'Monday', 'Tuesday', 'Wednesday', 'Thursday', 'Friday', 'Saturday'],
};
const MONTHS = {
  fr: ['janvier', 'février', 'mars', 'avril', 'mai', 'juin', 'juillet', 'août', 'septembre', 'octobre', 'novembre', 'décembre'],
  en: ['January', 'February', 'March', 'April', 'May', 'June', 'July', 'August', 'September', 'October', 'November', 'December'],
};

export const cap = (s: string) => s.charAt(0).toUpperCase() + s.slice(1);
export const shortDay = (key: string, lang: Lang) => cap(DAYS[lang][parseKey(key).getDay()]).slice(0, 3);
export const dayNumber = (key: string) => parseKey(key).getDate();

/** « lundi 24 novembre », « Monday, November 24 » */
export function longDay(key: string, lang: Lang): string {
  const d = parseKey(key);
  return lang === 'fr'
    ? `${DAYS.fr[d.getDay()]} ${d.getDate()} ${MONTHS.fr[d.getMonth()]}`
    : `${DAYS.en[d.getDay()]}, ${MONTHS.en[d.getMonth()]} ${d.getDate()}`;
}

/** « aujourd’hui », « demain » ou le jour complet, pour les phrases du chatbot. */
export function relativeDay(key: string, lang: Lang, now = new Date()): string {
  const today = dateKey(now);
  const tomorrow = dateKey(new Date(now.getFullYear(), now.getMonth(), now.getDate() + 1));
  if (key === today) return lang === 'fr' ? 'aujourd’hui' : 'today';
  if (key === tomorrow) return lang === 'fr' ? 'demain' : 'tomorrow';
  return lang === 'fr' ? DAYS.fr[parseKey(key).getDay()] : DAYS.en[parseKey(key).getDay()];
}

export const money = (n: number) => `${Math.round(n).toString().replace(/\B(?=(\d{3})+(?!\d))/g, ' ')} F`;

/** Remplace les valeurs réglables par l'admin : heure limite, nombre de plats à crédit, frais de dépannage. */
export function fill(lang: Lang, s: string): string {
  return s
    .split('{time}')
    .join(cutoffLabel(lang))
    .split('{max}')
    .join(String(MAX_CREDIT_DISHES))
    .split('{fee}')
    .join(String(Math.round(CREDIT_FEE_RATE * 100)));
}
